using Mulse.Modules;

namespace Service.Execution;

public sealed class RuntimeMulseState
{
    public List<string> PluginDirectories { get; set; } = [];

    public List<ManagedModulePackageDefinition> ManagedPackages { get; set; } = [];

    public List<PipelineDefinition> Pipelines { get; set; } = [];

    public List<FlowOrchestrationCheckpoint> OrchestrationCheckpoints { get; set; } = [];

    public List<FlowRetryState> PendingRetries { get; set; } = [];

    /// <summary>
    /// Values that resolve <c>{{config:reference}}</c> and <c>{{secret:reference}}</c> placeholder
    /// tokens generated by the BizTalk importer (and usable by any flow, hand-authored or imported).
    /// Stored with the rest of the runtime payloads under the same optional at-rest encryption.
    /// Secrets are not treated specially in storage, only in how the UI displays them (masked).
    /// </summary>
    public Dictionary<string, string> ConfigValues
    {
        get => _configValues;
        set => _configValues = new(value, StringComparer.OrdinalIgnoreCase);
    }

    private Dictionary<string, string> _configValues = new(StringComparer.OrdinalIgnoreCase);
}
